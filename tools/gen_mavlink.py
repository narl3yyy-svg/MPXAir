#!/usr/bin/env python3
"""Generate mpxair/mavlink/defs.py from the MAVLink XML message definitions.

Run from the MPXAir folder:  python3 tools/gen_mavlink.py
The generated file is checked in, so this only needs re-running when the XML
definitions are updated.
"""
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEF_DIR = os.path.join(ROOT, "mpxair", "mavlink", "definitions")
OUT = os.path.join(ROOT, "mpxair", "mavlink", "defs.py")

TYPE_SIZE = {
    "char": 1, "uint8_t": 1, "int8_t": 1, "uint16_t": 2, "int16_t": 2,
    "uint32_t": 4, "int32_t": 4, "float": 4, "uint64_t": 8, "int64_t": 8,
    "double": 8,
}


def x25(data, crc=0xFFFF):
    for b in data:
        tmp = b ^ (crc & 0xFF)
        tmp = (tmp ^ (tmp << 4)) & 0xFF
        crc = ((crc >> 8) ^ (tmp << 8) ^ (tmp << 3) ^ (tmp >> 4)) & 0xFFFF
    return crc


def parse_file(name, seen, messages, enums):
    if name in seen:
        return
    seen.add(name)
    tree = ET.parse(os.path.join(DEF_DIR, name))
    root = tree.getroot()
    for inc in root.findall("include"):
        parse_file(inc.text.strip(), seen, messages, enums)

    for en in root.iter("enum"):
        ename = en.get("name")
        e = enums.setdefault(ename, {"bitmask": en.get("bitmask") == "true", "entries": {}})
        auto = 0
        for ent in en.findall("entry"):
            v = ent.get("value")
            val = int(v, 0) if v is not None else auto
            auto = val + 1
            desc = (ent.findtext("description") or "").strip()
            params = {}
            for p in ent.findall("param"):
                idx = int(p.get("index"))
                params[idx] = {
                    "label": p.get("label") or "",
                    "units": p.get("units") or "",
                    "desc": (p.text or "").strip(),
                }
            e["entries"][val] = {"name": ent.get("name"), "desc": desc, "params": params}

    for msg in root.iter("message"):
        mid = int(msg.get("id"))
        mname = msg.get("name")
        fields = []
        ext = False
        for child in msg:
            if child.tag == "extensions":
                ext = True
                continue
            if child.tag != "field":
                continue
            t = child.get("type")
            arr = 0
            if "[" in t:
                t, n = t.split("[")
                arr = int(n.rstrip("]"))
            if t == "uint8_t_mavlink_version":
                t = "uint8_t"
            fields.append({
                "name": child.get("name"), "type": t, "arr": arr, "ext": ext,
                "enum": child.get("enum") or "", "units": child.get("units") or "",
            })
        base = [f for f in fields if not f["ext"]]
        exts = [f for f in fields if f["ext"]]
        # wire order: base fields sorted by element size (stable), then extensions
        base_sorted = sorted(base, key=lambda f: -TYPE_SIZE[f["type"]])
        crc_str = mname + " "
        crc = x25(crc_str.encode())
        for f in base_sorted:
            crc = x25((f["type"] + " ").encode(), crc)
            crc = x25((f["name"] + " ").encode(), crc)
            if f["arr"]:
                crc = x25(bytes([f["arr"]]), crc)
        crc_extra = (crc & 0xFF) ^ (crc >> 8)
        messages[mid] = {
            "name": mname, "crc_extra": crc_extra,
            "fields": [(f["name"], f["type"], f["arr"], f["ext"], f["enum"], f["units"])
                       for f in base_sorted + exts],
        }


def main():
    messages, enums = {}, {}
    parse_file("ardupilotmega.xml", set(), messages, enums)
    with open(OUT, "w") as fh:
        fh.write("# Generated by tools/gen_mavlink.py from the MAVLink XML definitions. Do not edit.\n")
        fh.write("# fields: (name, type, array_len, is_extension, enum, units) in wire order\n\n")
        fh.write("MESSAGES = {\n")
        for mid in sorted(messages):
            m = messages[mid]
            fh.write(f"    {mid}: ({m['name']!r}, {m['crc_extra']}, {m['fields']!r}),\n")
        fh.write("}\n\n")
        fh.write("ENUMS = {\n")
        for ename in sorted(enums):
            e = enums[ename]
            entries = {v: (d["name"], d["desc"]) for v, d in sorted(e["entries"].items())}
            fh.write(f"    {ename!r}: ({e['bitmask']!r}, {entries!r}),\n")
        fh.write("}\n\n")
        cmd = enums.get("MAV_CMD", {"entries": {}})["entries"]
        fh.write("# MAV_CMD id -> {param index: (label, units, description)}\n")
        fh.write("CMD_PARAMS = {\n")
        for v, d in sorted(cmd.items()):
            ps = {i: (p["label"], p["units"], p["desc"]) for i, p in sorted(d["params"].items())}
            fh.write(f"    {v}: {ps!r},\n")
        fh.write("}\n\n")
        # flat constants for convenience
        for ename in sorted(enums):
            for v, d in sorted(enums[ename]["entries"].items()):
                fh.write(f"{d['name']} = {v}\n")
    print(f"wrote {OUT}: {len(messages)} messages, {len(enums)} enums")


if __name__ == "__main__":
    sys.exit(main())
